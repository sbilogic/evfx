import { dirname,join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { allReleases } from './github.mjs';
import { selectReleases } from './release-selection.mjs';
import { loadJson,saveJson } from './sync-files.mjs';
const root=dirname(dirname(fileURLToPath(import.meta.url)));
const catalog=await loadJson(join(root,'catalog.json'));
const backfill=await loadJson(join(root,'release-notes.json'),{version:1,releases:{}});
if(backfill.version!==1||!backfill.releases||typeof backfill.releases!=='object')throw new Error('Invalid release note archive');
const lock=selectReleases(catalog,await allReleases(catalog.repository),backfill.releases);
if(!Object.keys(lock).length)throw new Error('No EVFX release manifests found; existing lock was preserved.');
await saveJson(join(root,'releases.lock.json'),lock);
console.log(`Refreshed ${Object.keys(lock).length} tools from GitHub Releases.`);
