import { dirname,join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { allReleases } from './github.mjs';
import { selectReleases } from './release-selection.mjs';
import { loadJson,saveJson } from './sync-files.mjs';
const root=dirname(dirname(fileURLToPath(import.meta.url)));
const catalog=await loadJson(join(root,'catalog.json'));
const lock=selectReleases(catalog,await allReleases(catalog.repository));
if(!Object.keys(lock).length)throw new Error('No EVFX release manifests found; existing lock was preserved.');
await saveJson(join(root,'releases.lock.json'),lock);
console.log(`Refreshed ${Object.keys(lock).length} tools from GitHub Releases.`);
